'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const FONT_URL='https://fonts.googleapis.com/css2?family=Manrope:wght@300;400;500;600;700&display=swap';
function quotedEnd(text,start){for(let i=start+1;i<text.length;i++){if(text[i]==='\\'){i++;continue}if(text[i]===text[start])return i+1}throw Error('Unterminated CSS string')}
function commentEnd(text,start){const end=text.indexOf('*/',start+2);assert.ok(end>=0,'Unterminated CSS comment');return end+2}
function tokenEnd(text,start,terminator){let depth=0;for(let i=start;i<text.length;i++){
 if(text.startsWith('/*',i)){i=commentEnd(text,i)-1;continue}if(text[i]==='"'||text[i]==="'"){i=quotedEnd(text,i)-1;continue}
 if(text[i]==='(')depth++;if(text[i]===')')depth--;if(text[i]===terminator&&depth===0)return i+1;
}throw Error('Unterminated CSS token')}
function compileCSS(root,entries,{readFile}={}){
 const state={fontFace:false,external:new Set(),inputs:[]},workspace=path.resolve(root);
 function fileCSS(file,chain=[]){
  const absolute=path.resolve(workspace,file);assert.ok(absolute.startsWith(workspace+path.sep),'CSS source outside project');
  file=path.relative(workspace,absolute).split(path.sep).join('/');assert.ok(!chain.includes(file),'CSS import cycle: '+[...chain,file].join(' -> '));
  const bytes=readFile?readFile(file):fs.readFileSync(absolute);assert.ok(Buffer.isBuffer(bytes),'CSS reader must return bytes');const text=bytes.toString('utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
  state.inputs.push({path:file,bytes:bytes.length,sha256:crypto.createHash('sha256').update(bytes).digest('hex')});
  let output='/* Source: '+file+' */\n',importsAllowed=true;
  for(let i=0;i<text.length;){
   if(text.startsWith('/*',i)){const end=commentEnd(text,i);output+=text.slice(i,end);i=end;continue}
   if(text[i]==='"'||text[i]==="'"){const end=quotedEnd(text,i);output+=text.slice(i,end);i=end;importsAllowed=false;continue}
   if(text[i]==='\\')throw Error('Unsupported escaped CSS identifier');
   if(/^@import\b/i.test(text.slice(i))){
    assert.ok(importsAllowed,'Unsupported CSS import after rules');const end=tokenEnd(text,i,';'),rule=text.slice(i,end),match=rule.match(/^@import\s+url\(\s*(["'])([^"']+)\1\s*\)\s*;$/i);
    assert.ok(match,'Unsupported CSS import syntax');const url=match[2];
    if(/^(?:[a-z][\w+.-]*:|\/\/)/i.test(url)){assert.equal(url,FONT_URL,'Unapproved external CSS import');assert.ok(!state.fontFace,'Cannot hoist font import across a preceding font-face');state.external.add(url)}
    else{assert.ok(!url.includes('\\')&&!/[?#]/.test(url),'Unsupported CSS import path');const next=new URL(url,'https://css.invalid/'+file).pathname.slice(1);output+=fileCSS(next,[...chain,file])}
    i=end;continue;
   }
   if(/^@(charset|namespace)\b/i.test(text.slice(i)))throw Error('Unsupported CSS charset/namespace');
   if(/^@font-face\b/i.test(text.slice(i)))state.fontFace=true;
   if(text.slice(i,i+4).toLowerCase()==='url('&&!/[\w-]/.test(text[i-1]||'')){
    const end=tokenEnd(text,i+3,')'),raw=text.slice(i+4,end-1).trim(),quote=/^["']/.test(raw)?raw[0]:'',value=quote?raw.slice(1,-1):raw;
    assert.ok(!quote||raw.endsWith(quote),'Malformed CSS URL');
    if(!/^(?:[a-z][\w+.-]*:|\/\/|\/|#)/i.test(value)){
     assert.ok(!value.includes('\\'),'Unsupported escaped relative CSS URL');const url=new URL(value,'https://css.invalid/'+file);output+='url('+quote+url.pathname+url.search+url.hash+quote+')';
    }else output+=text.slice(i,end);
    i=end;importsAllowed=false;continue;
   }
   if(!/\s/.test(text[i]))importsAllowed=false;output+=text[i++];
  }
  return output;
 }
 const body=entries.map(file=>fileCSS(file)).join('\n\n');
 const css=[...state.external].map(url=>'@import url("'+url+'");').join('\n')+'\n/* Generated by scripts/build-site.cjs; edit the source modules. */\n'+body+'\n';
 return {css,inputs:state.inputs,external:[...state.external]};
}
module.exports={compileCSS};
