const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const works = fs.readFileSync(path.join(root,'css/works.css'),'utf8');
const services = fs.readFileSync(path.join(root,'css/services.css'),'utf8');
const worksJs = fs.readFileSync(path.join(root,'js/works.js'),'utf8');
const html = fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(works, /\.sc-work-item:last-child\s*\{[^}]*height:calc\(var\(--works-height\) \+ 2 \* var\(--works-padding\)\)/s);
assert.match(works, /\.sc-work-frame\s*\{[^}]*box-shadow:none/s);
assert.match(works, /\.sc-work-item--front \.sc-work-frame\s*\{[^}]*box-shadow:/s);
assert.match(worksJs,/function updateFrontCard\(\)/);
assert.match(worksJs,/updateFrontCard\(\);/);
assert.match(services, /\.sc-services\s*\{[^}]*margin-top:0;/s);
assert.doesNotMatch(services, /margin-top:\s*-(?:75|55)svh/);
assert.equal((html.match(/class="sc-work-item"/g)||[]).length,6);
assert.equal((html.match(/class="sc-service-card"/g)||[]).length,6);
assert.ok(html.indexOf('id="works"')<html.indexOf('id="services"'));
console.log('PASS: Works->Services v38: no negative overlap, last sticky box sized to frame, single front shadow, unchanged 6+6 cards.');
