document.addEventListener("DOMContentLoaded",()=>{
(()=>{
  const header=document.getElementById('floatingHeader');
  const toggle=document.getElementById('menuToggle');
  const panel=document.getElementById('mobilePanel');
  const onScroll=()=>header.classList.toggle('is-scrolled',scrollY>18);
  addEventListener('scroll',onScroll,{passive:true});onScroll();
  function closeMenu(){panel.hidden=true;toggle.setAttribute('aria-expanded','false');toggle.setAttribute('aria-label','Открыть меню')}
  toggle.addEventListener('click',()=>{const open=panel.hidden;panel.hidden=!open;toggle.setAttribute('aria-expanded',String(open));toggle.setAttribute('aria-label',open?'Закрыть меню':'Открыть меню')});
  panel.querySelectorAll('a').forEach(a=>a.addEventListener('click',closeMenu));
  document.addEventListener('keydown',e=>{if(e.key==='Escape'&&!panel.hidden){const restore=panel.contains(document.activeElement);closeMenu();if(restore)toggle.focus({preventScroll:true})}});
  document.addEventListener('pointerdown',e=>{if(!header.contains(e.target))closeMenu()});
  addEventListener('resize',()=>{if(innerWidth>850)closeMenu()});
})();

    (()=>{
      const section=document.getElementById('audiences');
      const options=[...section.querySelectorAll('.audience-option')];
      const panels=[...section.querySelectorAll('.audience-card')];
      const visual=section.querySelector('.audience-visual');
      const interactive=section.querySelector('.audience-container');
      const touchOnly=matchMedia('(hover: none)');
      let activeIndex=null;
      let activationSource=null;
      let pointerFocus=null;
      let pointerX=null,pointerY=null,pointerMoved=false;
      let previousScroll=scrollY;

      function selectAudience(index,source='hover'){
        const active=Number.isInteger(index)&&index>=0&&index<options.length?index:null;
        activeIndex=active;
        activationSource=active===null?null:source;
        visual.classList.toggle('is-open',active!==null);
        options.forEach((button,i)=>{
          const selected=i===active;
          button.classList.toggle('is-active',selected);
          button.setAttribute('aria-pressed',String(selected));
        });
        panels.forEach((panel,i)=>{
          const selected=i===active;
          panel.classList.toggle('is-active',selected);
          panel.setAttribute('aria-hidden',String(!selected));
          panel.inert=!selected;
        });
      }
      // Track actual pointer coordinates, not pointerenter generated by scrolling.
      document.addEventListener('pointermove',e=>{
        pointerMoved=e.clientX!==pointerX||e.clientY!==pointerY;
        pointerX=e.clientX;pointerY=e.clientY;
      },{capture:true,passive:true});
      document.addEventListener('pointerup',()=>{pointerFocus=null;},{passive:true});
      document.addEventListener('pointercancel',()=>{pointerFocus=null;},{passive:true});
      options.forEach((button,index)=>{
        button.addEventListener('pointerdown',()=>{pointerFocus=button;},{passive:true});
        // Touch emits a compatibility mousedown after pointerup, before focus.
        button.addEventListener('mousedown',()=>{pointerFocus=button;},{passive:true});
        button.addEventListener('pointermove',e=>{
          if(pointerMoved&&(e.pointerType==='mouse'||e.pointerType==='pen')&&!touchOnly.matches){
            selectAudience(index,'hover');
          }
        },{passive:true});
        button.addEventListener('focus',()=>{
          // A touch's default focus must not open the card before tap-to-toggle.
          if(pointerFocus!==button) selectAudience(index,'focus');
        });
        button.addEventListener('blur',e=>{
          if(activationSource==='focus'&&!options.includes(e.relatedTarget)) selectAudience(null);
        });
        button.addEventListener('click',e=>{
          if(touchOnly.matches&&e.detail!==0){
            selectAudience(activeIndex===index?null:index,'tap');
          }else{
            selectAudience(index,e.detail===0?'focus':'hover');
          }
          pointerFocus=null;
        });
        button.addEventListener('keydown',e=>{
          pointerFocus=null;
          if(['ArrowDown','ArrowUp','Home','End'].includes(e.key)){
            e.preventDefault();
            const next=e.key==='Home'?0:e.key==='End'?options.length-1:
              (index+(e.key==='ArrowDown'?1:options.length-1))%options.length;
            options[next].focus({preventScroll:true});
            selectAudience(next,'focus');
          }
        });
      });
      interactive.addEventListener('pointerleave',()=>{
        if(activationSource==='hover') selectAudience(null);
      });
      document.addEventListener('pointerdown',e=>{
        if(touchOnly.matches&&!interactive.contains(e.target)) selectAudience(null);
      },{passive:true});
      document.addEventListener('keydown',e=>{
        if(e.key==='Escape'){
          selectAudience(null);
          if(options.includes(document.activeElement)) document.activeElement.blur();
        }
      });
      // This observer only dismisses mouse hover. It never chooses a category
      // and does not handle wheel, change Lenis, or register a ScrollTrigger.
      addEventListener('scroll',()=>{
        if(scrollY===previousScroll) return;
        previousScroll=scrollY;
        if(activationSource==='hover') selectAudience(null);
      },{passive:true});
      selectAudience(null);
    })();
});
